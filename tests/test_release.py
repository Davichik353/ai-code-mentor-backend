"""Release regressions. Run: python -m unittest discover -s tests -v."""
import os
import secrets
import sqlite3
import tempfile
import unittest
from unittest.mock import AsyncMock, patch

os.environ.setdefault('JWT_SECRET', secrets.token_urlsafe(48))
os.environ['REQUIRE_EMAIL_VERIFICATION'] = 'false'
from fastapi.testclient import TestClient
import main
from database import Database
from migrations import run_migrations
from performance import RateLimiter


class ReleaseTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.db = Database(self.tmp.name + '/db.sqlite')
        self.db_patch = patch.object(main, 'db', self.db)
        self.db_patch.start()
        main.registration_ip_limiter.clear()
        main.registration_email_limiter.clear()
        main.api_limiter.clear()
        main.auth_ip_limiter.clear()
        main.login_limiter.clear()
        main.reset_limiter.clear()
        main.analysis_limiter = RateLimiter(5, 60)
        main.cache.clear()
        self.client = TestClient(main.app)
        self.client.__enter__()
        self.a = self.register('alice@example.com')
        self.b = self.register('bob@example.com')

    def tearDown(self):
        self.client.__exit__(None, None, None)
        self.db_patch.stop()
        self.tmp.cleanup()

    def register(self, email):
        response = self.client.post('/auth/register', json={
            'email': email, 'password': 'Release-test-Password1!', 'display_name': email,
        })
        self.assertEqual(response.status_code, 201, response.text)
        return {'Authorization': 'Bearer ' + response.json()['access_token']}

    def test_todos_are_private_and_account_deletion_cleans_up(self):
        response = self.client.post('/todos', headers=self.a, json={'title': 'Private task'})
        self.assertEqual(response.status_code, 201)
        task = response.json()['id']
        self.assertEqual(self.client.get('/todos', headers=self.b).json(), [])
        self.assertEqual(self.client.patch('/todos/' + task, headers=self.b, json={'completed': True}).status_code, 404)
        self.assertEqual(self.client.delete('/todos/' + task, headers=self.b).status_code, 404)
        self.assertEqual(self.client.patch('/todos/' + task, headers=self.a, json={'completed': True}).status_code, 200)
        self.assertEqual(len(self.client.get('/todos?status=completed', headers=self.a).json()), 1)
        self.assertEqual(self.client.delete('/auth/account', headers=self.a).status_code, 200)
        with sqlite3.connect(self.db.db_path) as conn:
            self.assertEqual(conn.execute('SELECT count(*) FROM todos').fetchone()[0], 0)

    def test_analysis_lifecycle_and_personal_statistics(self):
        feedback = {'summary': 'Example feedback', 'critical': [], 'improvements': [], 'learning': [], 'good': []}
        # Provider is mocked: this tests API persistence and authorization, not live AI quality.
        with patch.object(main.analyzer, 'analyze', AsyncMock(return_value=feedback)):
            response = self.client.post('/analyze', headers=self.a, json={'code': 'print(42)'})
        self.assertEqual(response.status_code, 200, response.text)
        analysis = response.json()['id']
        self.assertEqual(self.client.get('/stats').status_code, 401)
        self.assertEqual(self.client.get('/stats', headers=self.a).json()['total_analyses'], 1)
        self.assertEqual(self.client.get('/stats', headers=self.b).json()['total_analyses'], 0)
        self.assertEqual(self.client.get('/analysis/' + analysis, headers=self.b).status_code, 404)
        self.assertEqual(self.client.delete('/analysis/' + analysis, headers=self.b).status_code, 404)
        self.assertEqual(self.client.get('/progress', headers=self.a).json()['total_analyses'], 1)
        self.assertEqual(self.client.delete('/analysis/' + analysis, headers=self.a).status_code, 200)
        self.assertEqual(self.client.get('/progress', headers=self.a).json()['total_analyses'], 0)

    def test_unavailable_ai_and_request_limits(self):
        with patch.object(main.analyzer, 'analyze', AsyncMock(return_value={'analysis_available': False, 'summary': 'Unavailable'})) as provider:
            for _ in range(5):
                response = self.client.post('/analyze', headers=self.a, json={'code': 'print(42)'})
                self.assertEqual(response.status_code, 503)
            response = self.client.post('/analyze', headers=self.a, json={'code': 'print(42)'})
            self.assertEqual(response.status_code, 429)
            self.assertGreater(int(response.headers['Retry-After']), 0)
            self.assertEqual(provider.await_count, 5)
        self.assertEqual(self.client.get('/history', headers=self.a).json()['total'], 0)

    def test_authorship_endpoint_requires_login_and_works_without_ai(self):
        payload = {'code': '# Generated by ChatGPT\nprint(42)', 'filename': 'sample.py'}
        self.assertEqual(self.client.post('/authorship', json=payload).status_code, 401)
        response = self.client.post('/authorship', headers=self.a, json=payload)
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.json()['status'], 'ai_use_declared')
        self.assertEqual(response.json()['signals'][0]['line'], 1)

    def test_repeated_health_and_migrations(self):
        self.db.init_db()
        run_migrations(self.db.db_path)
        from health import HealthChecker
        checker = HealthChecker(self.db.db_path)
        try:
            for _ in range(6):
                self.assertEqual(checker.check_database()['status'], 'ok')
        finally:
            checker.pool.close_all()


class LegacyDatabaseTests(unittest.TestCase):
    def test_ownerless_legacy_tasks_are_preserved_but_not_exposed(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = tmp + '/legacy.sqlite'
            with sqlite3.connect(path) as conn:
                conn.execute('CREATE TABLE todos (id TEXT PRIMARY KEY, title TEXT, description TEXT, completed INTEGER, created_at TEXT, updated_at TEXT)')
                conn.execute("INSERT INTO todos VALUES ('old', 'legacy', NULL, 0, '', '')")
            db = Database(path)
            db.init_db()
            db.init_db()
            self.assertEqual(db.get_todos('new-user'), [])
            with sqlite3.connect(path) as conn:
                self.assertEqual(conn.execute('SELECT count(*) FROM todos').fetchone()[0], 1)

    def test_database_path_environment(self):
        with tempfile.TemporaryDirectory() as tmp:
            with patch.dict(os.environ, {'DATABASE_PATH': tmp + '/data/app.sqlite'}):
                db = Database()
                db.init_db()
                self.assertTrue(os.path.isfile(db.db_path))
