import unittest
from authorship import inspect_authorship

class AuthorshipTests(unittest.TestCase):
    def test_explicit_comment_disclosure_has_line_evidence(self):
        result = inspect_authorship('# Generated by ChatGPT\nprint(42)')
        self.assertEqual(result['status'], 'ai_use_declared')
        self.assertEqual(result['signals'][0]['line'], 1)
        self.assertNotIn('probability', result)

    def test_strings_and_clean_code_do_not_prove_authorship(self):
        for code in ['print("# Generated by ChatGPT")', 'def add(a, b):\n    return a + b', '# not generated by AI\nprint(42)']:
            self.assertEqual(inspect_authorship(code)['status'], 'inconclusive')

    def test_unsupported_language_is_explicit(self):
        result = inspect_authorship('// Generated by AI', 'code.js', 'JavaScript')
        self.assertFalse(result['supported'])
        self.assertEqual(result['status'], 'inconclusive')

    def test_broken_python_is_inconclusive(self):
        self.assertEqual(inspect_authorship('"""unterminated')['status'], 'inconclusive')
